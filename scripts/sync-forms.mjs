#!/usr/bin/env node
/**
 * Regenerate the GitHub "New item" issue form from src/content/keywords.yaml, so that its
 * "Places" checkboxes always list the current places.
 *
 *   npm run sync:forms              # write .github/ISSUE_TEMPLATE/new-item.yml
 *   npm run sync:forms -- --check   # CI: fail if the form is out of date
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { stringify } from 'yaml';
import { loadKeywords } from './lib/classify.mjs';
import { formFields, issueFormYaml } from './lib/form.mjs';

const ROOT = new URL('../', import.meta.url).pathname;
const TARGET = join(ROOT, '.github/ISSUE_TEMPLATE/new-item.yml');

const header = '# Generated by `npm run sync:forms` from src/content/keywords.yaml — do not edit by hand.\n';
const content = header + stringify(issueFormYaml(formFields(loadKeywords(ROOT))), { lineWidth: 0 });

if (process.argv.includes('--check')) {
  const current = existsSync(TARGET) ? readFileSync(TARGET, 'utf8') : '';
  if (current !== content) {
    console.error('✗ The "New item" form is out of date with keywords.yaml. Run `npm run sync:forms` and commit the result.');
    process.exit(1);
  }
  console.log('✓ "New item" form is up to date');
} else {
  mkdirSync(dirname(TARGET), { recursive: true });
  writeFileSync(TARGET, content);
  console.log(`wrote ${TARGET.replace(ROOT, '')}`);
}
