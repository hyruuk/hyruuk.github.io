/* ---------- hyruuk.yaml ---------- */

const Word = z.object({ word: z.string(), evokes: z.string(), weight: z.number().min(0).default(1) });
const Hyruuk = z.object({
  template: z.string(),
  R: z.array(Word).min(1),
  U1: z.array(Word).min(1),
  U2: z.array(Word).min(1),
  K: z.array(Word).min(1),
  avoid: z.array(z.tuple([z.string(), z.string()])).default([]),
});
export const hyruuk = load(Hyruuk, hyruukRaw, 'src/data/hyruuk.yaml');
for (const [slot, letter] of [['R', 'R'], ['U1', 'U'], ['U2', 'U'], ['K', 'K']] as const) {
  for (const w of hyruuk[slot]) {
    if (!w.word.toUpperCase().startsWith(letter)) {
      throw new Error(`Invalid src/data/hyruuk.yaml\n  • ${slot}: "${w.word}" does not start with ${letter}`);
    }
  }
}
