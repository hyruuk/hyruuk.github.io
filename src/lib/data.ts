/**
 * Site settings and world data (src/data/*.yaml), parsed and validated at build time.
 * Errors name the file and the field, e.g. "src/data/regions.yaml → music.label: expected array".
 */
import { z } from 'astro/zod';
import { parse } from 'yaml';
import hyruukRaw from '../data/hyruuk.yaml?raw';
import regionsRaw from '../data/regions.yaml?raw';
import siteRaw from '../data/site.yaml?raw';
import timelineRaw from '../data/timeline.yaml?raw';
import worldAssets from '../data/world.assets.json';
import worldRaw from '../data/world.yaml?raw';

function load<T extends z.ZodType>(schema: T, raw: string, path: string): z.infer<T> {
  const result = schema.safeParse(parse(raw));
  if (!result.success) {
    const details = result.error.issues.map((i) => `  • ${i.path.join('.') || '(root)'}: ${i.message}`).join('\n');
    throw new Error(`Invalid ${path}\n${details}`);
  }
  return result.data;
}

const Localized = z.object({ en: z.string(), fr: z.string() });
export type Localized = z.infer<typeof Localized>;

/* ---------- site.yaml ---------- */

const Site = z.object({
  name: z.string(),
  handle: z.string(),
  url: z.url(),
  launched: z.boolean(),
  email: z.email(),
  role: Localized,
  position: Localized,
  quote: Localized,
  description: Localized,
  profiles: z.array(z.object({ kind: z.string(), label: z.string(), url: z.url() })),
  discord: z.object({
    name: z.string(),
    invite: z.union([z.literal(''), z.url()]),
    serverId: z.string(),
  }),
  cv: z.string(),
});
export const site = load(Site, siteRaw, 'src/data/site.yaml');

/* ---------- timeline.yaml (About page) ---------- */

const TextOrLocalized = z.union([z.string(), Localized]);
const Timeline = z.array(z.object({ when: z.union([z.string(), z.number()]).transform(String), what: TextOrLocalized, where: TextOrLocalized.optional() }));
export const timeline = load(Timeline, timelineRaw, 'src/data/timeline.yaml');
export function text(value: string | { en: string; fr: string } | undefined, lang: 'en' | 'fr'): string {
  if (value === undefined) return '';
  return typeof value === 'string' ? value : value[lang];
}

/* ---------- world.yaml / regions.yaml ---------- */

const Rect = z.tuple([z.number(), z.number(), z.number(), z.number()]);
const LookName = z.enum(['full', 'focus', 'backdrop', 'deep']);
const StageName = z.enum(['home', 'focus', 'backdrop']);
const CameraOverride = z.object({
  rect: Rect.optional(),
  fit: z.enum(['contain', 'cover']).optional(),
  align: z.tuple([z.number(), z.number()]).optional(),
  zoom: z.number().optional(),
});
const Camera = z.object({
  rect: Rect,
  fit: z.enum(['contain', 'cover']).default('cover'),
  align: z.tuple([z.number(), z.number()]).default([0.5, 0.5]),
  zoom: z.number().default(1),
  stage: StageName.optional(),
  look: LookName.optional(),
  portrait: CameraOverride.optional(),
});
export type CameraSpec = z.infer<typeof Camera> & { stage: z.infer<typeof StageName>; look: z.infer<typeof LookName> };

const World = z.object({
  units: z.tuple([z.number(), z.number()]),
  maxScale: z.number().default(4),
  looks: z.record(LookName, z.object({ dim: z.number(), vignette: z.number(), blur: z.number() })),
  cameras: z.record(z.string(), Camera),
});
export const world = load(World, worldRaw, 'src/data/world.yaml');

const Polygon = z.array(z.number()).refine((p) => p.length >= 6 && p.length % 2 === 0, {
  error: 'a polygon is a flat list of x,y pairs with at least 3 points',
});
const Region = z.object({
  polygons: z.array(Polygon).min(1),
  label: z.tuple([z.number(), z.number()]),
  camera: Camera,
});
const Extra = z.object({
  id: z.string(),
  page: z.string(),
  polygons: z.array(Polygon).min(1),
  label: z.tuple([z.number(), z.number()]),
});
const Regions = z.object({ extras: z.array(Extra).default([]) }).catchall(Region);
const regionsData = load(Regions, regionsRaw, 'src/data/regions.yaml');
export const regionExtras = regionsData.extras;
export const regions: Record<string, z.infer<typeof Region>> = Object.fromEntries(
  Object.entries(regionsData).filter(([k]) => k !== 'extras'),
) as Record<string, z.infer<typeof Region>>;
export type RegionData = z.infer<typeof Region>;

/** SVG path "d" for one or several polygons */
export function polygonsToPath(polygons: number[][]): string {
  return polygons
    .map((p) => {
      const pts: string[] = [];
      for (let i = 0; i < p.length; i += 2) pts.push(`${p[i]},${p[i + 1]}`);
      return `M${pts.join(' L')} Z`;
    })
    .join(' ');
}

